// draw text string, 1bpp fixed font
// Optimised (v3.0.4): same name/signature/output. When the whole string fits on
// the screen it is written through ONE window (6 window commands + start line)
// instead of one window per character (7 command bytes per character).
void draw_text_ssd1306( const char *text, font1bpp myfont, uint8_t col, uint8_t page,uint16_t color1)
{
	const uint16_t first = myfont.first, last = myfont.last;
	const uint8_t *fmap = myfont.fontmap;
	uint16_t cc, count = 0;
	char c;

	// printable characters in the (max 37 character) string
	for (cc=0; cc<=36 && (c=text[cc])!=0; ++cc)
		if ( ((uint16_t)c>=first) && ((uint16_t)c<=last) ) ++count;

	if ( (myfont.height == 8) && ( (uint16_t)col + count*(FIXEDFONT_WIDTH+1) <= SSD1306_W) )
	{
		// fast path: one window, glyph columns streamed back to back
		const uint8_t inv = (color1 == TEXT_INVERSE) ? 0xff : 0x00;
		if (count == 0) return;
		oled_setblock_ssd1306(col,page,(uint8_t)(count*(FIXEDFONT_WIDTH+1)),1);
		for (cc=0; cc<=36 && (c=text[cc])!=0; ++cc) {
			if ( ((uint16_t)c<first) || ((uint16_t)c>last) ) continue;
			const uint8_t *glyph = fmap + (uint16_t)(c-first)*FIXEDFONT_WIDTH;
			for (uint8_t x=0; x<FIXEDFONT_WIDTH; ++x)
				if ( !data_ssd1306( glyph[x] ^ inv ) ) return;
			if ( !data_ssd1306( inv ) ) return;		// blank spacing column
		}
		return;
	}

	// general path (other fonts / text running over the edge): one window per character
	uint16_t charcursor=0;
	for (cc=0; cc<=36 && (c=text[cc])!=0; ++cc) {
		if ( ((uint16_t)c>=first) && ((uint16_t)c<=last) ) {
			draw_font_ssd1306( (uint8_t *) (fmap + (uint16_t)(c-first)*FIXEDFONT_WIDTH),(uint8_t) col+charcursor,page,(uint8_t) FIXEDFONT_WIDTH, (uint8_t) myfont.height, color1) ;
			charcursor+= (FIXEDFONT_WIDTH+1);
		}
	}
}

// draw one letter of font
void draw_font_ssd1306(uint8_t *pSrc, uint8_t col, uint8_t page,uint8_t xSize, uint8_t ySize,uint16_t color)
{
	const uint8_t inv = (color == TEXT_INVERSE) ? 0xff : 0x00;
	const uint8_t rows = ySize/8;						// 1bpp = 8 pixels per byte
	oled_setblock_ssd1306(col,page,xSize+1, rows); 		// define writing block on oled x,y ,w, heigt in page
	for( uint8_t c=0;c<xSize;c++)
		for (uint8_t r=0;r<rows;r++)
			if ( !data_ssd1306( *(pSrc + c + (r*xSize/2)) ^ inv ) ) return;
	data_ssd1306( inv );								// blank spacing column
}

